from dataclasses import dataclass

from climb_ai.technique import Technique

VIDEO_DIR_NAME = "примеры техник"


@dataclass(frozen=True)
class Lesson:
    technique: str
    summary: str
    steps: tuple[str, ...]
    video: str = ""

    def as_dict(self):
        return {
            "название": self.technique,
            "суть": self.summary,
            "как": list(self.steps),
            "видео": self.video,
        }


